abc :: Pattern String
abc = "a b c"

showS :: Maybe Rational -> String
showS m = case m of
  Nothing -> "Nothing"
  Just r -> show (numerator r) ++ "/" ++ show (denominator r)

sh :: String -> Pattern a -> IO ()
sh name pat = putStrLn (name ++ " " ++ showS (steps pat) ++ " " ++ show (isJust (pureValue pat)))

tk :: Rational -> Integer
tk r = floor (r * 720720)

-- steps, then the onsets of cycles 0 and 1 in ticks
ev :: String -> Pattern String -> IO ()
ev name pat = putStrLn (name ++ " " ++ showS (steps pat) ++ " " ++ show (sort [(tk (start w), tk (stop w), value e) | e <- queryArc pat (Arc 0 2), eventHasOnset e, let w = wholeOrPart e]))

