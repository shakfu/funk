tk :: Rational -> Integer
tk r = floor (r * 46126080)

-- an Arc in ticks (F2)
ta :: Arc -> (Integer, Integer)
ta (Arc a b) = (tk a, tk b)

-- every event of p over [a, b), fragments included (F3)
qa :: String -> (x -> String) -> Pattern x -> Rational -> Rational -> IO ()
qa name r pat a b = putStrLn (name ++ " " ++ show (sort [(fmap ta (whole e), ta (part e), r (value e), contextPosition (context e)) | e <- queryArc pat (Arc a b)]))


fmt :: Double -> String
fmt x = show (round (x * 1e9) :: Integer)

-- the onsets of cycles [0, k), each cycle sorted
cycOn :: Int -> (a -> String) -> Pattern a -> [(Integer, Integer, String, [((Int, Int), (Int, Int))])]
cycOn k r p = concatMap one [0 .. k - 1]
  where
    one c = sort $ map (\e -> let Arc a b = wholeOrPart e in (tk a, tk b, r (value e), contextPosition (context e)))
              $ filter eventHasOnset $ queryArc p (Arc (fromIntegral c) (fromIntegral c + 1))

-- cycOn, each query with controls m
cycOnC :: Int -> (a -> String) -> ValueMap -> Pattern a -> [(Integer, Integer, String, [((Int, Int), (Int, Int))])]
cycOnC k r m p = concatMap one [0 .. k - 1]
  where
    one c = sort $ map (\e -> let Arc a b = wholeOrPart e in (tk a, tk b, r (value e), contextPosition (context e)))
              $ filter eventHasOnset $ query p (State (Arc (fromIntegral c) (fromIntegral c + 1)) m)

outC :: String -> Int -> (a -> String) -> [(String, Value)] -> Pattern a -> IO ()
outC name k r m p = putStrLn (name ++ " " ++ show (cycOnC k r (Map.fromList m) p))

out :: String -> Int -> (a -> String) -> Pattern a -> IO ()
out name k r p = putStrLn (name ++ " " ++ show (cycOn k r p))

-- values of a continuous pattern at the starts of quarter cycles
sampled :: String -> Pattern Double -> IO ()
sampled name p = putStrLn (name ++ " " ++ show [concatMap (fmt . value) (queryArc p (Arc t t)) | t <- [0, 1/4 .. 7/4]])

rI :: Int -> String
rI = show
rF :: Double -> String
rF = fmt
rS :: String -> String
rS = id

rN :: Note -> String
rN = fmt . unNote
rB :: Bool -> String
rB b = if b then "t" else "f"

rV :: Value -> String
rV v = case v of
  VF x -> "f" ++ fmt x
  VN (Note x) -> "f" ++ fmt x
  VI i -> "i" ++ show i
  VS x -> "s" ++ x
  VR x -> "f" ++ fmt (fromRational x)
  _ -> "?"

rC :: ValueMap -> String
rC m = concatMap (\(k, v) -> k ++ "=" ++ rV v ++ ";") (Map.toList m)

nums :: Pattern Int
nums = fastFromList [0, 1, 2, 3]
abcd :: Pattern String
abcd = fastFromList ["a", "b", "c", "d"]
chord :: Pattern Int
chord = stack [pure 0, pure 4, pure 7]
-- a Char literal (M3)
bpc :: Pattern Char -> Pattern Char
bpc x = x

-- a Bool literal, as Tidal's IsString parses it (M1)
bp :: Pattern Bool -> Pattern Bool
bp x = x
tf :: Pattern Bool
tf = fastFromList [True, False, True, True]
bdsn :: ControlPattern
bdsn = T.s (fastFromList ["bd", "sn"])

